class RenderError(Exception):
	pass


def plural(n, one, many):
	return f'{n} {one if n == 1 else many}'


def stats_html(counts):
	parts = [plural(counts['photos'], 'photo', 'photos'), plural(counts['stories'], 'story', 'stories')]
	if counts['places']:
		parts.append(plural(counts['places'], 'place', 'places'))
	ys = counts.get('years') or []
	if ys:
		parts.append(str(ys[0]) if ys[0] == ys[1] else f'{ys[0]}–{ys[1]}')
	return f'<p class="frames-stats mono">{esc(" · ".join(parts))}</p>'


def u(base, path):
	return esc(f'{base}/{path}')


def tile_img(base, src, alt, slug, idx):
	load = 'loading="eager" fetchpriority="high"' if idx == 0 else 'loading="eager"' if idx < 3 else 'loading="lazy"'
	return (f'<img src="{u(base, src["sq480"])}" srcset="{u(base, src["sq480"])} 480w, {u(base, src["sq960"])} 960w" '
		f'sizes="(min-width: 1248px) 400px, 33vw" width="960" height="960" alt="{esc(alt)}" {load} decoding="async" '
		f'style="view-transition-name: frame-{esc(slug)}" />')


def grid_html(items, base, indent=''):
	t = indent + '\t'
	lines = ['<ul class="frames-grid" role="list">']
	for i, it in enumerate(items):
		if it['type'] == 'photo':
			lines.append(f'{t}<li><a class="frame-tile" href="#{esc(it["slug"])}" data-slug="{esc(it["slug"])}" data-type="photo">')
			lines.append(f'{t}\t{tile_img(base, it["src"], it["alt"], it["slug"], i)}')
			lines.append(f'{t}\t<span class="frame-tile__meta"><span class="frame-tile__note">{esc(it["note"])}</span><span class="frame-tile__place mono">{PIN} {esc(it["place"])} · {it["year"]}</span></span>')
		else:
			c = it['cover']
			lines.append(f'{t}<li><a class="frame-tile frame-tile--story" href="frames/{esc(it["slug"])}.html" data-slug="{esc(it["slug"])}" data-type="story">')
			lines.append(f'{t}\t{tile_img(base, c["src"], c["alt"], it["slug"], i)}')
			lines.append(f'{t}\t{BADGE}')
			lines.append(f'{t}\t<span class="frame-tile__meta"><span class="frame-tile__note">{esc(it["summary"] or it["title"])}</span><span class="frame-tile__place mono">Story · {it["readMinutes"]} min read</span></span>')
		lines.append(f'{t}</a></li>')
	lines.append(f'{indent}</ul>')
	return '\n'.join(lines)


def fill_markers(page: str, name: str, content: str, path_label='frames.html') -> str:
	start, end = f'<!-- frames:{name} -->', f'<!-- /frames:{name} -->'
	if page.count(start) != 1 or page.count(end) != 1:
		raise RenderError(f'{path_label} must contain exactly one "{start}" and one "{end}" (found {page.count(start)} and {page.count(end)})')
	a = page.index(start) + len(start)
	b = page.index(end)
	if b < a:
		raise RenderError(f'{path_label}: "{end}" comes before "{start}"')
	line_start = page.rfind('\n', 0, page.index(start)) + 1
	indent = re.match(r'[ \t]*', page[line_start:]).group(0)
	if callable(content):
		content = content(indent)
	return page[:a] + '\n' + indent + content + '\n' + indent + page[b:]


